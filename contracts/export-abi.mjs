// Exports the contract ABIs from Foundry's build output to /abi, and regenerates the typed copy the
// frontend imports. Run `forge build` first. Usage: node export-abi.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const CONTRACTS = ["RobotRegistrar", "BoundsCREConsumer", "EvidenceAnchor"];

mkdirSync(join(root, "abi"), { recursive: true });
const abis = {};
for (const name of CONTRACTS) {
  const { abi } = JSON.parse(readFileSync(join(here, "out", `${name}.sol`, `${name}.json`), "utf8"));
  abis[name] = abi;
  writeFileSync(join(root, "abi", `${name}.json`), `${JSON.stringify(abi, null, 2)}\n`);
}

const ts = `// Generated by contracts/export-abi.mjs from RobotRegistrar. Do not edit.
export const guardianAbi = ${JSON.stringify(abis.RobotRegistrar, null, 2)} as const;
`;
writeFileSync(join(root, "src", "abi", "guardian.ts"), ts);
console.log(`Exported ${CONTRACTS.join(", ")} to /abi and src/abi/guardian.ts`);
